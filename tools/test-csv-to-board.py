def test_generator_refuses_a_theme_that_is_not_in_the_manifest(tmp):
    """The gate must be the BUNDLE stage, not the structural one.

    `validateDocument` checks shapes. Whether a theme is in themes/themes.json, and
    whether a gameType names a config that exists, are cross-reference checks that run
    only from `validateBundle`. A board with "theme": "marque" passes every shape rule and
    does not load. The first version of this tool called it valid and wrote it.
    """
    for field, value, word in (('theme', 'marque', 'themes.json'),
                               ('gameType', 'feudd', 'gametypes/')):
        m = load(MAP)
        m['board'] = dict(m['board'], **{field: value})
        mp = os.path.join(tmp, f'bad-{field}.map.json')
        open(mp, 'w', encoding='utf-8').write(json.dumps(m))
        games = os.path.join(tmp, f'bad-{field}-games')
        os.makedirs(games, exist_ok=True)
        manifest = os.path.join(games, 'games.json')
        open(manifest, 'w', encoding='utf-8').write(
            open(os.path.join(REPO, 'games', 'games.json'), encoding='utf-8').read())
        proc = run(mp, CSV, ('--games-dir', games, '--manifest', manifest, '--write'))
        check(f'a board whose {field} does not resolve is REFUSED, not written',
              proc.returncode != 0 and not os.path.exists(
                  os.path.join(games, 'revenue-feud.json')),
              f'exit {proc.returncode}')
        check(f'and the refusal points at {word}',
              word in proc.stderr, proc.stderr.strip()[:250])


