def test_zero_point_answer_is_reported(tmp):
    """The case that only appears once the survey grows — which is the point of the tool.

    At 17 responses every kept answer is worth at least 6. At ~290 a real answer with one
    vote apportions to 0: an unplayable row, permitted by the schema (value min is
    -1000000) and therefore invisible to both validation gates. Nothing but this warning
    stands between that and a board on a projector.
    """
    with open(CSV, encoding='utf-8') as fh:
        rows = fh.read().splitlines()
    header, body = rows[0], rows[1:]
    # One response repeated until a single-vote answer rounds to nothing.
    grown = os.path.join(tmp, 'big.csv')
    open(grown, 'w', encoding='utf-8').write(
        '\n'.join([header] + body + [body[0]] * 280) + '\n')
    proc = run(MAP, grown)
    check('a kept answer that apportions to 0 points is REPORTED, not shipped silently',
          'apportions to 0 points' in proc.stdout,
          proc.stdout.strip()[:400] or proc.stderr.strip()[:200])


