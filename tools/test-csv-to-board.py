def test_both_files_land_or_neither(tmp):
    """A board written without its manifest line IS the defect this tool prevents.

    The first version wrote the board first, outside the try block: a failing manifest
    write left a valid, served, unreachable board behind and printed a traceback.
    """
    games = os.path.join(tmp, 'atomic')
    os.makedirs(games, exist_ok=True)

    # The manifest must READ fine and fail to WRITE, or the run never reaches the write
    # phase and the mutation is untestable. The first version of this assertion made the
    # manifest path a directory — which fails in build_manifest, before any file is
    # written, so removing the rollback left it green. A real manifest in a read-only
    # DIRECTORY is the fixture that separates the two: os.replace needs write permission
    # on the directory, not on the file.
    locked = os.path.join(tmp, 'locked')
    os.makedirs(locked, exist_ok=True)
    manifest = os.path.join(locked, 'games.json')
    with open(os.path.join(REPO, 'games', 'games.json'), encoding='utf-8') as fh:
        open(manifest, 'w', encoding='utf-8').write(fh.read())
    os.chmod(locked, 0o555)
    try:
        proc = run(MAP, CSV, ('--games-dir', games, '--manifest', manifest, '--write'))
    finally:
        os.chmod(locked, 0o755)

    check('a failing manifest write fails the run', proc.returncode != 0,
          f'exit was {proc.returncode}')
    check('and leaves NO board file behind — not a valid, unreachable one',
          not os.path.exists(os.path.join(games, 'revenue-feud.json')),
          'the board landed without its manifest entry: the exact defect C20 prevents')
    check('and leaves no .tmp debris',
          not [f for f in os.listdir(games) if f.endswith('.tmp')],
          f'debris: {os.listdir(games)}')
    check('and reports it without a traceback',
          'Traceback' not in proc.stderr, proc.stderr.strip()[:200])


def test_a_long_response_fails_clearly(tmp):
    """Survey text is effectively untrusted: one real response runs to 90 words.

    It reaches the board only if a map author makes it a label, which is the realistic
    mistake. What must not happen is a confusing failure.
    """
    m = load(MAP)
    m['columns'][0]['answers'][0] = {'label': 'x' * 5000, 'from': ['Elon Musk']}
    mp = os.path.join(tmp, 'long.map.json')
    open(mp, 'w', encoding='utf-8').write(json.dumps(m))
    proc = run(mp)
    check('an over-length answer label is refused', proc.returncode != 0,
          f'exit was {proc.returncode}')
    check('and the refusal names the limit rather than dumping 5000 characters',
          'characters' in proc.stderr and len(proc.stderr) < 4000,
          f'stderr was {len(proc.stderr)} bytes')


