def test_manifest_entry_is_a_valid_manifest(tmp, manifest_path):
    """M31 — the entry is asserted AS A MANIFEST, by the thing that consumes manifests.

    This is `M28` in a new tool. The editor once emitted a games.json line built from the
    wrong field and never escaped; the assertion that caught it built a manifest from the
    line and validated that, rather than inspecting the model it came from.
    """
    if not manifest_path:
        return
    r = validate('games', manifest_path)
    check('the generated games.json is a valid manifest, per the engine',
          r.returncode == 0, r.stderr.strip()[:300])

    m = load(MAP)

    # The shipped map sets title == pickerKey, so it CANNOT distinguish an implementation
    # that keys the manifest on the picker key from one that keys it on the title. That is
    # the tautology `M28` shipped behind. A fixture where the two differ is the only kind
    # that tests anything, so the assertion builds one.
    distinct = dict(m)
    distinct['board'] = dict(m['board'],
                             title='Revenue Feud (Ward Night Edition)',
                             pickerKey='Revenue Feud')
    dp = os.path.join(tmp, 'distinct.map.json')
    open(dp, 'w', encoding='utf-8').write(json.dumps(distinct))
    dgames = os.path.join(tmp, 'distinct-games')
    os.makedirs(dgames, exist_ok=True)
    dm = os.path.join(dgames, 'games.json')
    open(dm, 'w', encoding='utf-8').write(open(manifest_path, encoding='utf-8').read())
    dproc = run(dp, CSV, ('--games-dir', dgames, '--manifest', dm, '--write'))
    dmanifest = load(dm) if dproc.returncode == 0 else {'games': {}}
    filename = m['board']['filename']
    check('the manifest entry is keyed on pickerKey, asserted where it DIFFERS from title',
          dmanifest['games'].get('Revenue Feud') == filename
          and 'Revenue Feud (Ward Night Edition)' not in dmanifest['games'],
          f'manifest keys: {sorted(dmanifest["games"])}')

    manifest = load(manifest_path)
    key = m['board']['pickerKey']
    check('the shipped map\'s board is reachable from the generated manifest',
          manifest['games'].get(key) == filename,
          f'games[{key!r}] = {manifest["games"].get(key)!r}')

    # A key the manifest schema refuses must not be producible from a legal map. The board
    # TITLE is free-form and may carry an em dash or a quote; the picker key is what lands.
    hostile = dict(m)
    hostile['board'] = dict(m['board'], title='Revenue "Feud" — \\ / <script>')
    hp = os.path.join(tmp, 'hostile.map.json')
    open(hp, 'w', encoding='utf-8').write(json.dumps(hostile))
    games = os.path.join(tmp, 'hostile-games')
    os.makedirs(games, exist_ok=True)
    hm = os.path.join(games, 'games.json')
    open(hm, 'w', encoding='utf-8').write(open(manifest_path, encoding='utf-8').read())
    proc = run(hp, CSV, ('--games-dir', games, '--manifest', hm, '--write'))
    ok = proc.returncode == 0 and validate('games', hm).returncode == 0
    check('a board title full of quotes and backslashes still yields a valid manifest',
          ok, proc.stderr.strip()[:300])


def test_generator_refuses_to_write_an_invalid_board(tmp):
    """M32 — the validator gate, asserted THROUGH THE GENERATOR.

    The first version of this assertion drove tools/validate-board.mjs directly and
    checked that it refuses a 16-column board. It does. But that tests the CLI, not the
    tool: M32 deleted the gate from csv-to-board.py outright and the suite stayed green at
    25/25, because nothing here ever asked whether the GENERATOR consults it. So the
    mutation is applied where it lives — a map that produces an over-cap board — and the
    assertion reads the generator's exit code and the absence of the file.
    """
    m = load(MAP)
    m['columns'] = m['columns'] * 2  # 16 columns; the cap is 12
    mp = os.path.join(tmp, 'over.map.json')
    open(mp, 'w', encoding='utf-8').write(json.dumps(m))

    games = os.path.join(tmp, 'over-games')
    os.makedirs(games, exist_ok=True)
    manifest = os.path.join(games, 'games.json')
    open(manifest, 'w', encoding='utf-8').write(
        open(os.path.join(REPO, 'games', 'games.json'), encoding='utf-8').read())
    before = open(manifest, encoding='utf-8').read()

    proc = run(mp, CSV, ('--games-dir', games, '--manifest', manifest, '--write'))
    check('the generator REFUSES to write a board the engine would reject',
          proc.returncode != 0, f'exit was {proc.returncode}')
    check('and it says so in the engine\'s own words, naming the cap',
          '12 columns' in proc.stderr, proc.stderr.strip()[:300])
    check('a refused run leaves no board file behind',
          not os.path.exists(os.path.join(games, 'revenue-feud.json')))
    check('a refused run leaves games.json untouched',
          open(manifest, encoding='utf-8').read() == before)


