def test_no_respondent_text_reaches_the_board(board):
    """Rewritten: the original could not fail.

    It asserted `'@' not in json.dumps(board)`. Answer text comes from the map's `label`
    and never from the CSV, and the email column is in `ignoreColumns`, so that was true
    by construction. Review proved it: a mutation putting RAW RESPONDENT TEXT on the board
    (`a['label']` -> `a['from'][0]`) left the PII assertion green.

    So the assertion now names the actual respondent strings — the two email addresses and
    the 90-word rant — and checks none of them appear. Those differ between a board built
    from map labels and one built from raw responses, which is the only property worth
    asserting here.
    """
    if not board:
        return
    text = json.dumps(board, ensure_ascii=False)
    with open(CSV, encoding='utf-8') as fh:
        raw = fh.read()
    leaked = [s for s in raw.replace('"', ',').split(',')
              if '@' in s and '.' in s and len(s) > 8]
    check('no respondent email address reaches the generated board',
          not any(e in text for e in leaked),
          f'leaked one of {leaked}')
    check('and no raw response text reaches it either — labels come from the MAP',
          'fully saturated with evil' not in text and 'the spine' not in text,
          'raw respondent wording is on the board')


def test_manifest_preserves_every_other_board(tmp, manifest_path):
    """The behaviour that would be catastrophic, and that 28/28 did not cover.

    Review's mutation MX1 reduced build_manifest to `{picker_key: filename}` — every other
    board vanishes from the picker — and the suite stayed green, because the assertions
    asked only "is it valid" and "is MY key present". Both are true of the wiping
    implementation. That is the fixture-satisfies-both pattern the register already
    records twice.
    """
    if not manifest_path:
        return
    before = load(os.path.join(REPO, 'games', 'games.json'))['games']
    after = load(manifest_path)['games']
