"""Assertions for tools/csv-to-board.py. Chore C20.

    python3 tools/test-csv-to-board.py

Prints a count, because an exit code cannot show a suite that stopped running.

Each assertion here exists to catch a NAMED mutation (M29-M33 in the register), and each
mutation was applied to the shipped code and seen to fail before its row was written. The
project has five recorded cases of an assertion that read correctly, passed, and could not
detect the behaviour it named. Two habits from those, kept deliberately here:

  * assertions read the tool's real OUTPUT — the generated bytes, the process exit code —
    rather than re-deriving what the answer ought to be. An assertion that recomputes its
    expectation cannot see the path that produces the real one;
  * the manifest assertion builds a manifest FROM the generated entry and validates THAT
    (`M28`), instead of trusting the model the entry came from.
"""

import json
import os
import subprocess
import sys
import tempfile

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOOL = os.path.join(REPO, 'tools', 'csv-to-board.py')
MAP = os.path.join(REPO, 'examples', 'revenue-feud.map.json')
CSV = os.path.join(REPO, 'examples', 'revenue_responses_17.csv')

PASSED = []
FAILED = []


def check(name, condition, detail=''):
    (PASSED if condition else FAILED).append(name)
    if not condition:
        print(f'  FAIL  {name}' + (f'\n        {detail}' if detail else ''))


def run(map_path=MAP, csv_path=CSV, extra=()):
    """Run the generator as a SUBPROCESS — the way a user runs it, exit code and all."""
    return subprocess.run(
        [sys.executable, TOOL, map_path, '--csv', csv_path, *extra],
        capture_output=True, text=True, cwd=REPO)


def generate(tmp, map_path=MAP, csv_path=CSV):
    """Generate into a scratch directory and read back the FILES, not the objects."""
    games = os.path.join(tmp, 'games')
    os.makedirs(games, exist_ok=True)
    manifest = os.path.join(games, 'games.json')
    with open(os.path.join(REPO, 'games', 'games.json'), encoding='utf-8') as fh:
        seed = fh.read()
    open(manifest, 'w', encoding='utf-8').write(seed)
    proc = run(map_path, csv_path, ('--games-dir', games, '--manifest', manifest, '--write'))
    return proc, games, manifest


def load(path):
    with open(path, encoding='utf-8') as fh:
        return json.load(fh)


def validate(kind, path):
    return subprocess.run(
        ['node', os.path.join(REPO, 'tools', 'validate-board.mjs'), kind, path],
        capture_output=True, text=True, cwd=REPO)


